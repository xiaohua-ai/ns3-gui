// C++ 字符串字面量转义 —— **单一来源**。
//
// 为什么必须集中：产物里有多个位置把用户输入拼进 C++ 字符串字面量（节点名 `Names::Add("…")`、
// 半实物 tap 名、遥测消息）。只要有一处漏转义，名字里一个 `"` 就能提前闭合字面量把产物打废
// （编译报错），而 `\` 更糟 —— 它不报错，只是**静默改变语义**。
// 各写一份必然分叉，故统一到这里。
//
// 反斜杠必须先转，否则会把后面新生成的转义符再转一遍。
export function cppLiteral(s: string): string {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t');
}
